#!/usr/bin/env python3
"""Provide basic arithmetic functions for import."""


def add(a, b):
    """Return a + b."""
    return a + b


def sub(a, b):
    """Return a - b."""
    return a - b


def mul(a, b):
    """Return a * b."""
    return a * b


def div(a, b):
    """Return a / b."""
    return a / b
